"""
Whole-brain calcium trace analysis — preliminary dataset.

For each animal: per-frame fluid ROI = top TOP_PERCENT% of pixels in each
frame's max-intensity projection. Saves per-animal results under
outputs/cache/{animal}.npz so re-runs only compute new animals. Drops the
first BLEACH_CUTOFF_FRAME frames for stats and compares BlaC vs
BlaC-Catalytically Dead with Mann-Whitney on post-bleach raw mean.

QC videos are generated by the separate make_qc_videos.py script.

Analysis is byte-identical to analyze_calcium_traces_finaldata.py; only the
data-source path and the animal-to-condition mapping at the top differ.
"""

